export function applyLessonExtras(lesson: Lesson): Lesson {
  const extraData = EXTRAS[lesson.id];
  if (!extraData) return lesson;
  const problems = lesson.problems.map((p) => {
    const hints = extraData.hints?.[p.id];
    if (!hints?.length) return p;
    return { ...p, hints: [...(p.hints ?? []), ...hints] };
  });
  return {
    ...lesson,
    purpose: extraData.purpose ?? lesson.purpose,
    nonexample: extraData.nonexample ?? lesson.nonexample,
    problems: extraData.extraProblems ? [...problems, ...extraData.extraProblems] : problems,
  };
}
